const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const url=pathToFileURL(path.join(__dirname,'2026JB-KL.html')).href;
  const errors=[];
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000}});
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(url);
    assert.equal(await page.locator('#cab-audio-music').evaluate(track=>track.paused),true,'Music waits for interaction');
    await page.locator('#open-itinerary').click();
    await page.waitForFunction(()=>document.querySelector('#cab-audio-music').currentTime>.05);
    const metadata=await page.evaluate(()=>[...document.querySelectorAll('audio')].map(track=>({name:track.id,duration:track.duration,error:track.error?.code||null})));
    assert.ok(metadata.every(track=>Number.isFinite(track.duration)&&track.duration>0&&!track.error));
    console.log('Decoded audio:',JSON.stringify(metadata));
    await page.locator('#sheet-sound').click();
    assert.ok(await page.evaluate(()=>[...document.querySelectorAll('audio')].every(track=>track.muted)));
    await page.locator('#sheet-sound').click();
    const musicTime=await page.locator('#cab-audio-music').evaluate(track=>track.currentTime);
    await page.keyboard.press('Escape');
    await page.locator('#lever-grip').click();
    await page.waitForFunction(()=>document.querySelector('#cab').dataset.phase==='departing' && document.querySelector('#cab-audio-running').currentTime>.05 && document.querySelector('#cab-audio-running').volume>.03);
    assert.equal(await page.locator('#cab-audio-running').evaluate(track=>track.loop),true);
    await page.screenshot({path:path.join(__dirname,'previews/driver-departing.png')});
    await page.waitForFunction(()=>document.querySelector('#cab').dataset.phase==='cruising');
    assert.ok(await page.locator('#cab-audio-music').evaluate(track=>track.volume<.2),'Music ducks under train');
    await page.waitForFunction(()=>document.querySelector('#cab').dataset.phase==='arriving' && document.querySelector('#cab-audio-arrival').currentTime>.03);
    await page.screenshot({path:path.join(__dirname,'previews/driver-arriving.png')});
    await page.waitForFunction(()=>document.querySelector('#itinerary-dialog').open);
    assert.equal(await page.locator('#cab-audio-running').evaluate(track=>track.paused),true,'Running loop stops at station');
    assert.equal(await page.locator('#cab-audio-music').evaluate(track=>track.loop),true);
    assert.ok(await page.locator('#cab-audio-music').evaluate((track,time)=>track.currentTime>time,musicTime),'Music continues across journey and popup');
    await page.keyboard.press('Escape');
    await page.locator('#cab-sound summary').click();
    await page.locator('#sound-mute').click();
    assert.ok(await page.evaluate(()=>[...document.querySelectorAll('audio')].every(track=>track.muted)));
    await page.locator('#sound-music').evaluate(input=>{input.value='40';input.dispatchEvent(new Event('input',{bubbles:true}));});
    await page.reload();
    assert.equal(await page.locator('#sound-mute').getAttribute('aria-pressed'),'true','Mute preference persists');
    assert.equal(await page.locator('#sound-music').inputValue(),'40');
    await page.locator('#cab-sound summary').click();
    await page.locator('#sound-mute').click();
    await page.waitForFunction(()=>!document.querySelector('#cab-audio-music').paused);
    await page.locator('#cab-sound summary').click();
    await page.locator('#lever-grip').click();
    await page.waitForFunction(()=>document.querySelector('#cab-audio-running').currentTime>.02);
    await page.evaluate(()=>{
      window.testHidden=true;
      Object.defineProperty(document,'hidden',{configurable:true,get:()=>window.testHidden});
      document.dispatchEvent(new Event('visibilitychange'));
    });
    assert.ok(await page.evaluate(()=>[...document.querySelectorAll('audio')].every(track=>track.paused)),'Hidden page pauses all tracks');
    await page.evaluate(()=>{window.testHidden=false;document.dispatchEvent(new Event('visibilitychange'));});
    await page.waitForFunction(()=>!document.querySelector('#cab-audio-running').paused);
    await page.locator('#skip-ride').click();
    await page.waitForFunction(()=>document.querySelector('#itinerary-dialog').open);
    assert.equal(await page.locator('#cab-audio-running').evaluate(track=>track.paused),true);
    await page.keyboard.press('Escape');
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.locator('#lever-grip').click();
    await page.waitForFunction(()=>document.querySelector('#cab').dataset.day==='2' && document.querySelector('#itinerary-dialog').open);
    await page.waitForFunction(()=>document.querySelector('#cab-audio-arrival').currentTime>.02);
    assert.equal(await page.locator('#cab-audio-running').evaluate(track=>track.paused),true,'Instant arrival leaves no running loop');
    await page.locator('#sheet-sound').click();
    await page.keyboard.press('Escape');
    await page.locator('#lever-grip').click();
    await page.waitForFunction(()=>document.querySelector('#cab').dataset.day==='3'&&document.querySelector('#itinerary-dialog').open);
    await page.locator('#sheet-sound').click();
    await page.waitForFunction(()=>document.querySelector('#cab-audio-music').volume>.35);
    await page.setViewportSize({width:390,height:844});
    await page.keyboard.press('Escape');
    await page.locator('#cab-sound summary').click();
    const bounds=await page.locator('.sound-settings').boundingBox();
    assert.ok(bounds.x>=0&&bounds.x+bounds.width<=390,'Phone sound controls fit screen');
    await page.screenshot({path:path.join(__dirname,'previews/driver-sound-mobile.png')});
    assert.deepEqual(errors,[]);
    const fallback=await browser.newContext({reducedMotion:'reduce'});
    await fallback.addInitScript(()=>Object.defineProperty(window,'localStorage',{get(){throw new DOMException('Blocked','SecurityError');}}));
    const backup=await fallback.newPage();
    await backup.route('**/audio/*.mp3',route=>route.abort());
    await backup.goto(url);
    await backup.locator('#lever-grip').click();
    await backup.waitForFunction(()=>document.querySelector('#cab').dataset.day==='1'&&document.querySelector('#itinerary-dialog').open);
    assert.match(await backup.locator('.activities-table').textContent(),/Skyline Luge/);
    console.log('Passed native MP3 playback, first-gesture music, three journey phases, running loop/arrival cue timing, ducking, popup continuity, mute/volume persistence, skip/reduced-motion cleanup, phone controls and unavailable-audio fallback.');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
